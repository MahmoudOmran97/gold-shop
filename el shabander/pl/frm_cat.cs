        private void btn_delete_Click(object sender, EventArgs e)
        {

            toast toast = new toast();
            dialog dialog = new dialog();
            try
            {
                id = Convert.ToInt32(tileView1.GetFocusedRowCellValue("id"));
                var tb_stuk = db.tb_stuk.FirstOrDefault(x => x.id == id);

                if (tb_stuk == null)
                {
                    dialog.Width = this.Width;
                    dialog.txt_capthion.Text = "الصنف غير موجود.";
                    dialog.Show();
                    return;
                }

                // التحقق إذا كانت الكمية أكبر من صفر
                if (tb_stuk.stuk_qt > 0)
                {
                    MessageBox.Show("لا يمكن حذف هذا الصنف لأنه يحتوي على كمية في المخزن.", "تنبيه", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                    return;
                }

                var rs = MessageBox.Show("عملية حذف", "هل انت متأكد من هذه العملية؟", MessageBoxButtons.YesNo);
                if (rs == DialogResult.Yes)
                {
                    db.Entry(tb_stuk).State = EntityState.Deleted;
                    db.SaveChanges();

                    toast.txt_caption.Text = "تم الحذف بنجاح";
                    toast.Show();
                    updata_data();
                }
            }
            catch
            {
                dialog.Width = this.Width;
                dialog.txt_capthion.Text = "لا يوجد صنف لحذفه";
                dialog.Show();
            }
        }

