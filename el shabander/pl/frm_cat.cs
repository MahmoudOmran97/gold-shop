        private void btn_edit_Click(object sender, EventArgs e)
        {
            pl.frm_stuck_add frm_Cat_Add = new frm_stuck_add();
            id = Convert.ToInt32(tileView1.GetFocusedRowCellValue("id"));
            var tb_stuk = db.tb_stuk.Where(x => x.id == id).FirstOrDefault();
            frm_Cat_Add.edt_name.Text = tb_stuk.stuk_name;
            frm_Cat_Add.edt_name_old.Text = tb_stuk.stuk_name;
            frm_Cat_Add.edt_code.Text = tb_stuk.code;
            frm_Cat_Add.edt_cat.DataSource = db.TB_cat.Select(x => x.cat_name).ToList();
            frm_Cat_Add.edt_cat.Text=tb_stuk.stuk_cat;
            frm_Cat_Add.unit_small.Text = tb_stuk.stuk_type;
            frm_Cat_Add.unit_big.Text = tb_stuk.stuk_supp;
            frm_Cat_Add.edt_type.Text = tb_stuk.type_fact;
            frm_Cat_Add.edt_big.Text= tb_stuk.stuk_qtfacttotal.ToString();
            frm_Cat_Add.id = id;
            frm_Cat_Add.btn_add.Text = "تعديل";
            frm_Cat_Add.Show();
        }
       

